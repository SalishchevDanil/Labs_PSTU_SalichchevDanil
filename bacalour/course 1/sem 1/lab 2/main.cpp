#include <iostream> //подключаю библиотеку для управления вводом / выводом
#include <clocale> //подключаю библиотеку для локализации
#include <cmath> //подключаю библиотеку math для математических функций

using namespace std; //подключаю пространство имён std

int main(){
    setlocale(LC_ALL, ".65001"); // подключаю русскую локализацию
    
    // s - сумма, n - номер элемента, an - текущий элемент, ac - точность
    // Инициализируем an для n=1: a_1 = e^1 * 100^(-1) = e / 100
    long double s = 0, n = 1, an = exp(1.0L) / 100.0L; 
    const long double ac = 0.0001L; 

    // Пока текущий элемент больше или равен точности (по модулю)
    while(fabs(an) >= ac) 
    {
        s += an; //добавляем элемент к сумме
        n++; //увеличиваем номер шага
        
        // Вычисляем новый n-ный элемент по рекуррентной формуле:
        // a_n = a_{n-1} * e / 100^(2n-1)
        an = an * exp(1.0L) / powl(100.0L, 2.0L * n - 1.0L); 
    }
    
    // Выводим информацию о результате работы программы
    cout << "Вариант 20. Выполнил: Салищев Данил РИС-26-3б" << endl;
    cout << "Сумма элементов, удовлетворяющих точности " << (double)ac << ", равна = " << (double)s << endl; 
    
    return 0; //возвращаем 0, как результат верного выполнения блока main()
}

/* Анализ задачи
 Исходная формула: an = e^n * 100^(-n^2)
 Первый член при n=1: a1 = e / 100
 Рекуррентная формула: a(n) = a(n-1) * e / (100^(2n-1))
 В цикле while суммируем элементы, пока они не станут меньше точности 10^-4
 Выводим результат
*/