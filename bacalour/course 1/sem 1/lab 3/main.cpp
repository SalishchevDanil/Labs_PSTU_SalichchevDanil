#include <iostream> //библиотека для ввода и вывода
#include <cmath> //математическая библиотека для pow, exp и tgamma
#include <clocale> //библиотека для локализации
using namespace std; //используем пространство имён std

int main(){
    setlocale(LC_ALL, ".65001"); //включаем русский язык
    cout << "Введите a и b через пробел: ";
    double a,b; cin >> a >> b; //вводим параметры a и b
    double k = (b-a)/10, n = 30, se = 0, sn = 0, cur;
    /* k - это шаг в цикле
    n - количество элементов для суммы (по варианту 30)
    se и sn - суммы для точности и для заданного n */

    double& x = a; //для удобства ссылка на a

    for(x; x <= b; x += k){ //перебор чисел от a до b с шагом k
        cout << "X = " << x << " "; //вывод текущего x
        
        // вычисляем текущее значение (член ряда для моего варианта)
        cur = pow(x/2.0, n) * (n*n + 1) / tgamma(n+1); 
        
        if(n > 0){ sn += cur; n--; } //увеличение sn
        if(x > 0.1 && x < 1) se += cur; //увеличение se

        //вывод текущих сумм:
        cout << "Xn = " << sn << " ";
        cout << "Xe = " << se << " ";
        //вывод точного значения Y (по формуле моего варианта)
        cout << "Y = " << (x*x/4.0 + x/2.0 + 1.0) * exp(x/2.0) << endl;
    }

    //вывод результатов:
    cout << endl << "Результаты:" << endl;
    cout << "Сумма для условия n <= 30 = " << sn << endl;
    cout << "Сумма для условия 0.1 < x < 1 = " << se << endl;
    return 0;
}