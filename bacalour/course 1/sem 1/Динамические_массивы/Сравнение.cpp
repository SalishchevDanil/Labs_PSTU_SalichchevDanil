#include <iostream>
using namespace std;
int main(){
    int n; cin >> n;
    //int a[n]; - ошибка (требуется константа) - статический массив
    int* m = new int[n]; // динамический массив

    //Пусть статический массив состоит из 5 элементов
    int a[5];
    //Пробуем внести меньше/больше элементов в a и m
    //for(int i = 0; i < 7 ++i) cin >> a[i]; - ошибка выход за граниы
    for(int i = 0; i < 3; ++i) cin >> a[i]; // 3 элемента запишутся - остальные нули
    // Введём больше меньше элементов в массив m
    for(int i = 0; i < n + 3; ++i) cin >> m[i];// нет ошибки, мы просто уходим в свободную оперативную память
    for(int i = 0; i < n+3; ++i) cout << m[i] << " ";// либо выведится как введено, либо мусорное значение
    cout << endl;

    for(int i = 0; i < n - 3; ++i) cin >> m[i];//ошибки нет, всё нормально
    for(int i = 0; i < n; ++i) cout << m[i] << " ";//выведится часть массива и мусор
    cout << endl;

    delete m;
    return 0;
}