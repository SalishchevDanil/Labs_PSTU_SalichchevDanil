int a = 12;

int* ptr = &a;    // ptr — это указатель, он хранит адрес переменной a.
                  // То есть ptr "смотрит" на a.

int copy = *ptr;  // *ptr — это разыменование, то есть значение по адресу,
                  // то есть само a (12). Просто копируем это значение в copy.
                  // copy — отдельная переменная, с a никак не связана.

(*ptr)++;         // Опять разыменовываем ptr и увеличиваем на 1 то, на что он смотрит,
                  // то есть саму a. Скобки важны: без них ++ применился бы к ptr.
                  // Теперь a = 13, а copy так и осталось 12.

std::cout << a << " " << copy;  // Выведет: 13 12