using namespace std;
int a = 5, b = 8;

int& r = a;       // r — ссылка на a (второе имя для a).
int& s = a;       // s — тоже ссылка на a. И r, и s — псевдонимы одного и того же a.
int copy = a;     // copy — обычная переменная, в неё просто скопировали значение a (5).
                  // С этого момента copy живёт отдельно и с a не связано.

r = b;            // Через r присваиваем a значение b (8). Теперь a = 8, b = 8.
                  // copy по-прежнему 5 — его никто не трогал.

s += 2;           // Через s (а это тот же a) прибавляем 2. Теперь a = 10.
                  // b = 8, copy = 5.

b = copy;         // b присваиваем значение copy (5). Теперь b = 5.

cout << a << " " << b << " "
     << r << " " << s << " " << copy;
                  // a = 10, b = 5, r = a = 10, s = a = 10, copy = 5.
                  // Выведет: 10 5 10 10 5