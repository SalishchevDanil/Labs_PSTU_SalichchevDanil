using namespace std;
int a = 4, b = 9;

int* p = &a;      // p — указатель, хранит адрес a, то есть смотрит на a.
int* q = p;       // q копирует адрес из p, значит q тоже смотрит на a.
int& r = *p;      // *p — это сам a. r — ссылка на a, то есть второе имя для a

p = &b;           // Теперь p смотрит на b. Но q по-прежнему смотрит на a,
                  // а r по-прежнему это a.

*q += *p;         // *q — это a (4), *p — это b (9). Значит a = 4 + 9 = 13.
                  // b пока не тронуто.

*p = r - 3;       // *p — это b, r — это a (13). Значит b = 13 - 3 = 10.

q = p;            // q теперь тоже смотрит на b (как и p). На a больше никто
                  // из указателей не смотрит, но r всё ещё ссылается на a.

*q += r;          // *q — это b (10), r — это a (13). Значит b = 10 + 13 = 23.

cout << a << " " << b << " " << r;  // a = 13, b = 23, r — это a, то есть 13.
                                    // Выведет: 13 23 13