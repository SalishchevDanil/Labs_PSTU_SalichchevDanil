using namespace std;
int a = 2, b = 5, c = 8;

int* p = &a;      // p — указатель, смотрит на a.
int& r = a;       // r — ссылка на a (второе имя для a, привязано навсегда).
int copy = *p;    // *p — это a (2). Копируем значение в copy.
                  // copy — отдельная переменная, дальше с a не связано.

*p = b;           // *p — это a, присваиваем a значение b (5). Теперь a = 5.

p = &c;           // Теперь p смотрит на c. (r по-прежнему это a!)

r = *p;           // r — это a, *p — это c (8). Значит a = 8.

*p = b + copy;    // *p — это c, b + copy = 5 + 2 = 7. Значит c = 7.

p = &b;           // Теперь p смотрит на b.

*p = r - copy;    // *p — это b, r — это a (8), copy = 2.
                  // b = 8 - 2 = 6.

r++;              // r — это a, увеличиваем a на 1. a = 9.

cout << a << " " << b << " " << c << " " << copy;
                  // a = 9, b = 6, c = 7, copy = 2.
                  // Выведет: 9 6 7 2