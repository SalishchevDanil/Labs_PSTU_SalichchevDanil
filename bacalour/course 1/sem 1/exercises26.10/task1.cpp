int a = 10;
int b = 20;

int& r = a;   // r — это ссылка для a.


r = b;        // Тут r не становится ссылкой на b.
              // Просто значение b (20) копируется в тот объект, на который смотрит r,
              // а r смотрит на a. Значит теперь a = 20, b = 20.

r++;          // Увеличиваем на 1 то, на что ссылается r, то есть a.
              // Получается a = 21, b так и осталось 20.

std::cout << a << " " << b;  // Выведет: 21 20